export function getFormationBySlug(slug: string): FormationItem | undefined {
  const normalized = slug.toLowerCase().trim();
  return FORMATIONS.find(
    (f) => f.slug === normalized || (f.aliases && f.aliases.includes(normalized))
  );
}

export function getFormationsByDomain(domainId: string): FormationItem[] {
  if (domainId === "all" || !domainId) return FORMATIONS;
  return FORMATIONS.filter((f) => f.domainId === domainId);
}
